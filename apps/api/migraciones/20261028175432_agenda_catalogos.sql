-- +goose Up
-- Agenda (I2, fase 3): zonas, cuadrillas, técnicos con turnos, ausencias y capacidad diaria por
-- tipo de orden, y las citas (con la ventana acordada con el cliente) de las órdenes programadas.
CREATE SCHEMA IF NOT EXISTS agenda;

-- Zonas. El id es el de Argos para las zonas espejo (origen argos, de integracion.argos_zonas:
-- zona_id sigue siendo el id de Argos en tickets, órdenes, servicios y alcances) y sale de
-- agenda.zonas_locales_seq (desde 10^12, lejos de los ids de Argos) para las zonas locales.
-- origen migrada: un zona_id que ya estaba en tickets, órdenes o alcances sin catálogo
-- (migración 20261028175434); si luego llega de Argos con el mismo id, pasa a origen argos.
-- poligono: GeoJSON (Polygon o MultiPolygon) propio de Iris, opcional, también en las de Argos.
CREATE SEQUENCE agenda.zonas_locales_seq START WITH 1000000000000;

CREATE TABLE agenda.zonas (
    id              bigint      PRIMARY KEY,
    empresa_id      bigint,
    origen          text        NOT NULL CHECK (origen IN ('argos', 'local', 'migrada')),
    nombre          text        NOT NULL CHECK (length(nombre) BETWEEN 1 AND 120),
    poligono        jsonb       CHECK (poligono IS NULL OR jsonb_typeof(poligono) = 'object'),
    activa          boolean     NOT NULL DEFAULT true,
    sincronizado_en timestamptz,
    version         integer     NOT NULL DEFAULT 1,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX zonas_empresa_idx ON agenda.zonas (empresa_id, nombre);

-- Cuadrillas (equipos de técnicos). Identity BY DEFAULT: la migración de huérfanos conserva los
-- ids que ya estaban en tickets, órdenes y alcances.
CREATE TABLE agenda.cuadrillas (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id bigint,
    nombre     text        NOT NULL CHECK (length(nombre) BETWEEN 1 AND 120),
    activa     boolean     NOT NULL DEFAULT true,
    version    integer     NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX cuadrillas_nombre_uq ON agenda.cuadrillas (empresa_id, lower(nombre)) NULLS NOT DISTINCT;

-- Zonas que atiende una cuadrilla (sin filas = todas las de su empresa).
CREATE TABLE agenda.cuadrilla_zonas (
    cuadrilla_id bigint      NOT NULL REFERENCES agenda.cuadrillas (id) ON DELETE CASCADE,
    zona_id      bigint      NOT NULL REFERENCES agenda.zonas (id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (cuadrilla_id, zona_id)
);
CREATE INDEX cuadrilla_zonas_zona_idx ON agenda.cuadrilla_zonas (zona_id);

-- Ficha de técnico: una por usuario (la persona: sus turnos, ausencias y citas valen en todas
-- las empresas en que opera, nucleo.usuarios_empresas). bodega_id es la de Argos (materiales).
CREATE TABLE agenda.tecnicos (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    usuario_id   bigint           NOT NULL UNIQUE REFERENCES nucleo.usuarios (id),
    cuadrilla_id bigint           REFERENCES agenda.cuadrillas (id),
    bodega_id    bigint,
    habilidades  text[]           NOT NULL DEFAULT '{}',
    base_lat     double precision,
    base_lon     double precision,
    activo       boolean          NOT NULL DEFAULT true,
    version      integer          NOT NULL DEFAULT 1,
    created_at   timestamptz      NOT NULL DEFAULT now(),
    updated_at   timestamptz      NOT NULL DEFAULT now(),
    CHECK ((base_lat IS NULL) = (base_lon IS NULL)),
    CHECK (base_lat IS NULL OR (base_lat BETWEEN -90 AND 90 AND base_lon BETWEEN -180 AND 180))
);
CREATE INDEX tecnicos_cuadrilla_idx ON agenda.tecnicos (cuadrilla_id) WHERE cuadrilla_id IS NOT NULL;

-- Turnos semanales en hora local (America/Guatemala): día ISO (1 = lunes … 7 = domingo), inicio
-- y fin del mismo día (fin hasta 24:00; un turno nocturno se parte en dos).
CREATE TABLE agenda.turnos (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tecnico_id bigint      NOT NULL REFERENCES agenda.tecnicos (id) ON DELETE CASCADE,
    dia        smallint    NOT NULL CHECK (dia BETWEEN 1 AND 7),
    inicio     time        NOT NULL,
    fin        time        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (fin > inicio)
);
CREATE INDEX turnos_tecnico_idx ON agenda.turnos (tecnico_id, dia, inicio);

-- Ausencias (vacaciones, enfermedad…): rango en UTC. Anular deja la fila (historial).
CREATE TABLE agenda.ausencias (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tecnico_id  bigint      NOT NULL REFERENCES agenda.tecnicos (id),
    inicio      timestamptz NOT NULL,
    fin         timestamptz NOT NULL,
    motivo      text        NOT NULL CHECK (motivo IN ('vacaciones', 'enfermedad', 'capacitacion', 'permiso', 'otro')),
    detalle     text        NOT NULL DEFAULT '',
    creada_por  bigint      REFERENCES nucleo.usuarios (id),
    anulada_en  timestamptz,
    anulada_por bigint      REFERENCES nucleo.usuarios (id),
    version     integer     NOT NULL DEFAULT 1,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (fin > inicio)
);
CREATE INDEX ausencias_tecnico_idx ON agenda.ausencias (tecnico_id, inicio) WHERE anulada_en IS NULL;

-- Capacidad diaria (día local) de un técnico o de una cuadrilla, por tipo de orden (tipo_id null
-- = todos los tipos): cupos (citas) y/o minutos programados. Sin fila = sin límite (solo turnos).
CREATE TABLE agenda.capacidades (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tecnico_id   bigint      REFERENCES agenda.tecnicos (id) ON DELETE CASCADE,
    cuadrilla_id bigint      REFERENCES agenda.cuadrillas (id) ON DELETE CASCADE,
    tipo_id      bigint      REFERENCES campo.tipos_orden (id),
    cupos        integer     CHECK (cupos IS NULL OR cupos > 0),
    minutos      integer     CHECK (minutos IS NULL OR minutos > 0),
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(tecnico_id, cuadrilla_id) = 1),
    CHECK (cupos IS NOT NULL OR minutos IS NOT NULL)
);
CREATE UNIQUE INDEX capacidades_uq ON agenda.capacidades (tecnico_id, cuadrilla_id, tipo_id) NULLS NOT DISTINCT;

-- Cita de una orden programada: técnico (usuario), inicio y fin estimados y la ventana de
-- llegada acordada con el cliente. Una por orden (reprogramar la mueve; el historial queda en
-- campo.orden_eventos). Ocupa la agenda mientras la orden está programada, en camino o en sitio.
CREATE TABLE agenda.citas (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    orden_id       bigint      NOT NULL UNIQUE REFERENCES campo.ordenes (id),
    empresa_id     bigint,
    tecnico_id     bigint      NOT NULL REFERENCES nucleo.usuarios (id),
    tipo_id        bigint      NOT NULL REFERENCES campo.tipos_orden (id),
    inicio         timestamptz NOT NULL,
    fin            timestamptz NOT NULL,
    ventana_inicio timestamptz,
    ventana_fin    timestamptz,
    version        integer     NOT NULL DEFAULT 1,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    CHECK (fin > inicio),
    CHECK ((ventana_inicio IS NULL) = (ventana_fin IS NULL)),
    CHECK (ventana_fin IS NULL OR ventana_fin > ventana_inicio)
);
CREATE INDEX citas_tecnico_idx ON agenda.citas (tecnico_id, inicio);
CREATE INDEX citas_empresa_inicio_idx ON agenda.citas (empresa_id, inicio);

-- Las órdenes que ya estaban programadas (main) tienen su cita: sin ventana.
INSERT INTO agenda.citas (orden_id, empresa_id, tecnico_id, tipo_id, inicio, fin)
SELECT id, empresa_id, tecnico_id, tipo_id, programada_inicio,
       coalesce(programada_fin, programada_inicio + interval '1 hour')
FROM campo.ordenes
WHERE tecnico_id IS NOT NULL AND programada_inicio IS NOT NULL;

