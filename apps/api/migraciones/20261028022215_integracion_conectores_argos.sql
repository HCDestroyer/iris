-- +goose Up
-- Conectores con ArgosISP (y más adelante Horus), webhooks entrantes e instantáneas de lectura
-- de Argos (contratos/argosisp.md §1.3, §2.2 y §2.3; CLAUDE.md §3 y §4).

-- Un conector por enlace de conexión canjeado. El token atk_… y el secreto del webhook van
-- cifrados con IRIS_CLAVE_CIFRADO (AES-256-GCM, atados a la fila) y nunca salen por la API.
-- Nace apagado; un administrador lo activa. A lo más uno activo por sistema.
CREATE TABLE integracion.conectores (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sistema                 text        NOT NULL CHECK (sistema IN ('argosisp', 'horus')),
    base_url                text        NOT NULL,
    origen                  text        NOT NULL CHECK (origen IN ('enlace_remoto', 'enlace_local')),
    token_cifrado           bytea       NOT NULL,
    secreto_webhook_cifrado bytea       NOT NULL,
    remoto_id               text,                                   -- id de la conexión del otro lado
    empresas                bigint[]    NOT NULL DEFAULT '{}',      -- empresas que cubre el token
    estado                  text        NOT NULL DEFAULT 'apagado' CHECK (estado IN ('apagado', 'activo')),
    creado_por              bigint      REFERENCES nucleo.usuarios (id),
    activado_en             timestamptz,
    activado_por            bigint      REFERENCES nucleo.usuarios (id),
    ultimo_webhook_en       timestamptz,
    version                 integer     NOT NULL DEFAULT 1,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX conectores_activo_uq ON integracion.conectores (sistema) WHERE estado = 'activo';

-- Códigos de los enlaces de conexión que genera Iris (https://<iris>/conectar#<codigo>):
-- 15 min, un solo uso; se guarda solo el SHA-256.
CREATE TABLE integracion.codigos_conexion (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sistema     text        NOT NULL CHECK (sistema IN ('argosisp', 'horus')),
    codigo_hash bytea       NOT NULL UNIQUE,
    expira_en   timestamptz NOT NULL,
    usado_en    timestamptz,
    conector_id bigint      REFERENCES integracion.conectores (id),
    creado_por  bigint      REFERENCES nucleo.usuarios (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Webhooks entrantes: se guardan primero (deduplicados por X-Webhook-Id) y se procesan en un
-- job de River (CLAUDE.md §3).
CREATE TABLE integracion.entrantes (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    conector_id  bigint      NOT NULL REFERENCES integracion.conectores (id),
    webhook_id   text        NOT NULL,
    evento       text        NOT NULL,
    empresa_id   bigint,
    payload      jsonb       NOT NULL,
    ocurrido_en  timestamptz,
    recibido_en  timestamptz NOT NULL DEFAULT now(),
    procesado_en timestamptz,
    resultado    text        CHECK (resultado IN ('aplicado', 'ignorado')),
    intentos     integer     NOT NULL DEFAULT 0,
    error        text,
    request_id   text        NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (conector_id, webhook_id)
);
CREATE INDEX entrantes_pendientes_idx ON integracion.entrantes (id) WHERE procesado_en IS NULL;

-- Instantáneas de lectura de Argos (§2.2): solo lo que Iris muestra. El id es el de Argos.
-- sincronizado_en es la hora en que se pidió a Argos: una lectura más vieja no pisa una nueva.
CREATE TABLE integracion.argos_clientes (
    id              bigint PRIMARY KEY,
    empresa_id      bigint           NOT NULL,
    codigo          text             NOT NULL DEFAULT '',
    nombre          text             NOT NULL,
    telefono        text             NOT NULL DEFAULT '',
    direccion       text             NOT NULL DEFAULT '',
    lat             double precision,
    lon             double precision,
    zona_id         bigint,
    estado          text             NOT NULL DEFAULT '',
    sincronizado_en timestamptz      NOT NULL,
    created_at      timestamptz      NOT NULL DEFAULT now(),
    updated_at      timestamptz      NOT NULL DEFAULT now()
);
CREATE INDEX argos_clientes_empresa_idx ON integracion.argos_clientes (empresa_id, nombre);

CREATE TABLE integracion.argos_servicios (
    id              bigint PRIMARY KEY,
    empresa_id      bigint           NOT NULL,
    cliente_id      bigint           NOT NULL REFERENCES integracion.argos_clientes (id) ON DELETE CASCADE,
    codigo          text             NOT NULL DEFAULT '',
    plan_id         bigint,
    plan_nombre     text             NOT NULL DEFAULT '',
    router_id       bigint,
    router_nombre   text             NOT NULL DEFAULT '',
    zona_id         bigint,
    zona_nombre     text             NOT NULL DEFAULT '',
    ip              text             NOT NULL DEFAULT '',
    direccion       text             NOT NULL DEFAULT '',
    lat             double precision,
    lon             double precision,
    estado          text             NOT NULL DEFAULT '',
    sincronizado_en timestamptz      NOT NULL,
    created_at      timestamptz      NOT NULL DEFAULT now(),
    updated_at      timestamptz      NOT NULL DEFAULT now()
);
CREATE INDEX argos_servicios_cliente_idx ON integracion.argos_servicios (cliente_id);

CREATE TABLE integracion.argos_zonas (
    id              bigint PRIMARY KEY,
    empresa_id      bigint      NOT NULL,
    nombre          text        NOT NULL,
    sincronizado_en timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE integracion.argos_routers (
    id              bigint PRIMARY KEY,
    empresa_id      bigint           NOT NULL,
    nombre          text             NOT NULL,
    zona_id         bigint,
    lat             double precision,
    lon             double precision,
    sincronizado_en timestamptz      NOT NULL,
    created_at      timestamptz      NOT NULL DEFAULT now(),
    updated_at      timestamptz      NOT NULL DEFAULT now()
);

