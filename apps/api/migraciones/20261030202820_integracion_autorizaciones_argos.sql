-- Autorizaciones en curso: una por clic en «Conectar con Argos». Del state se guarda solo el
-- SHA-256; el code_verifier va cifrado con IRIS_CLAVE_CIFRADO (atado a la fila) y nunca sale del
-- servidor. 10 min, un solo uso y ligada a la sesión del panel que la inició.
CREATE TABLE integracion.autorizaciones (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sistema             text        NOT NULL CHECK (sistema IN ('argosisp')),
    state_hash          bytea       NOT NULL UNIQUE,
    verificador_cifrado bytea,                          -- NULL una vez usada
    panel_url           text        NOT NULL,
    usuario_id          bigint      NOT NULL REFERENCES nucleo.usuarios (id) ON DELETE CASCADE,
    sesion_id           bigint      NOT NULL REFERENCES nucleo.sesiones (id) ON DELETE CASCADE,
    expira_en           timestamptz NOT NULL,
    usado_en            timestamptz,
    conector_id         bigint      REFERENCES integracion.conectores (id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX autorizaciones_sesion_idx ON integracion.autorizaciones (sesion_id);

